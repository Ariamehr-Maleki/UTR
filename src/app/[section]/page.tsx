import Link from "next/link";
import { notFound } from "next/navigation";
import { publicRecords } from "@/lib/data";
const sections: Record<string, [string, string]> = {
  opportunities: [
    "فرصت‌های پژوهشی",
    "فراخوان‌ها و فرصت‌های تأییدشده برای همکاری علمی.",
  ],
  journals: [
    "نشریات علمی",
    "راهنمای دسترسی به نشریات؛ این سامانه جایگزین سامانه انتشار مجلات نیست.",
  ],
  resources: [
    "کتابخانه و منابع علمی",
    "منابع منتخب و پیوند خدمات رسمی؛ خدمات امانت کتاب در UTR ارائه نمی‌شود.",
  ],
  news: [
    "خبرها و دستاوردها",
    "خبرهای منتشرشده معاونت پژوهش و فناوری دانشکدگان فارابی.",
  ],
  about: [
    "درباره UTR و ارتباط با ما",
    "پلتفرم جامع معاونت پژوهش و فناوری دانشکدگان فارابی دانشگاه تهران",
  ],
  privacy: [
    "حریم خصوصی",
    "اطلاعات پژوهشی و آموزشی شما، با دسترسی محدود و هدف مشخص نگهداری می‌شود.",
  ],
  policy: ["قوانین مشارکت", "ضوابط مشارکت در باشگاه پژوهشیاران"],
  club: ["باشگاه پژوهشیاران", "یک نشست، یک خلاصه، یک قدم جلوتر"],
  verify: ["استعلام گواهی", "شناسه یکتای گواهی را وارد کنید."],
};
export default async function Section({
  params,
}: {
  params: Promise<{ section: string }>;
}) {
  const { section } = await params;
  const info = sections[section];
  if (!info) notFound();
  const directory = ["opportunities", "journals", "resources", "news"].includes(
    section,
  );
  const rows = await publicRecords("content", section);
  return (
    <div className="container">
      <header className="page-head">
        <h1>{info[0]}</h1>
        <p>{info[1]}</p>
      </header>
      <div className="content">
        {directory ||
        (["about", "privacy", "policy"].includes(section) &&
          rows.length > 0) ? (
          <>
            {rows.length ? (
              rows.map((r) => (
                <article className="resource-row" key={r.id}>
                  <div>
                    <h2>
                      <Link href={`/${section}/${r.id}`}>{r.title}</Link>
                    </h2>
                    <p>{r.description}</p>
                  </div>
                  {r.external_url && (
                    <a
                      href={r.external_url}
                      target="_blank"
                      rel="noopener noreferrer"
                    >
                      خدمت رسمی
                    </a>
                  )}
                </article>
              ))
            ) : (
              <div className="empty">
                <strong>هنوز موردی منتشر نشده است</strong>
                <p>
                  پس از بررسی و انتشار مسئول مربوط، اطلاعات این بخش در دسترس
                  قرار می‌گیرد.
                </p>
                <Link href="/">بازگشت به صفحه اصلی</Link>
              </div>
            )}
          </>
        ) : section === "club" || section === "policy" ? (
          <div className="prose">
            <h2>از حضور تا ارزیابی</h2>
            <ol>
              <li>
                عضویت دانشجویان کارشناسی، کارشناسی ارشد و دکتری پس از تأیید
                وضعیت دانشجویی امکان‌پذیر است.
              </li>
              <li>
                در رویداد مورد تأیید باشگاه شرکت کنید. ثبت‌نام به‌تنهایی تأیید
                حضور نیست.
              </li>
              <li>
                خلاصه‌ای دست‌نویس، خوانا و یک‌صفحه‌ای روی فرم تعیین‌شده رویداد
                بنویسید. تحویل فیزیکی لازم نیست.
              </li>
              <li>
                تا پایان همان هفته، تصویر یا اسکن را بارگذاری و یک درس مرتبط از
                نیمسال جاری و استاد تأییدشده آن را انتخاب کنید. زمان دقیق مهلت
                در صفحه رویداد درج می‌شود.
              </li>
              <li>
                استاد برای هر رویداد امتیازی بین صفر و یک تعیین می‌کند. این سقف
                برای هر رویداد است و سقف تجمیعی نیمسال نیست.
              </li>
            </ol>
            <h2>ارجاع و اصلاح</h2>
            <p>
              تنها امتیاز دقیقاً صفر، امکان ارجاع به استاد واجد شرایط دیگری را
              فراهم می‌کند. هر امتیاز مثبت، حتی کسری، ارجاع دوباره را قفل
              می‌کند. تغییر فایل، عنوان، درس یا مشخصات حساب این قفل را باز
              نمی‌کند. بازگشت به دلیل نامرتبط بودن درس، با ارزیابی صفر متفاوت
              است.
            </p>
            <p>
              اصلاح خلاصه با همان استاد ادامه می‌یابد. اعتراض، به‌خودی‌خود قفل
              پرونده را باز نمی‌کند. معاونت پژوهشی مرجع نهایی اختلاف‌ها و
              اصلاحات استثنایی است.
            </p>
            <div className="notice">
              اعطای امتیاز کامل تضمین نمی‌شود. ده رویداد مستقل، در صورت دریافت
              امتیاز کامل برای هر یک، می‌تواند ده امتیاز در مجموع داشته باشد.
              اعمال آن در نمره رسمی درس تابع سیاست آموزشی مؤسسه است.
            </div>
            <Link className="button" href="/auth/register">
              ساخت حساب و درخواست عضویت
            </Link>
          </div>
        ) : section === "privacy" ? (
          <div className="prose">
            <h2>دسترسی به داده‌ها</h2>
            <p>
              خلاصه‌ها در فضای خصوصی نگهداری می‌شوند. دانشجو به پرونده خود و
              استاد به ارجاع مجاز خود دسترسی دارد. دسترسی اداری به دامنه مسئولیت
              مصوب محدود است.
            </p>
            <h2>رضایت و انتشار</h2>
            <p>
              عضویت در جدول مشارکت عمومی اختیاری است. نمره دانشگاهی، ارزیابی صفر
              و علت رد عمومی نمی‌شود. انتشار خلاصه به رضایت جداگانه و حذف
              اطلاعات شخصی نیاز دارد.
            </p>
            <h2>درخواست‌های شما</h2>
            <p>
              برای اصلاح داده، اعتراض یا درخواست حذف از بخش پشتیبانی حساب
              استفاده کنید. حذف سوابق آموزشی تابع تعهد نگهداری مصوب است؛ مدت
              قطعی نگهداری پیش از شروع بهره‌برداری اعلام می‌شود.
            </p>
          </div>
        ) : section === "about" ? (
          <div className="prose">
            <h2>یک مسیر مشترک برای خدمات پژوهشی</h2>
            <p>
              UTR دسترسی به خدمات پژوهشی، رویدادها، فرصت‌ها، نشریات، منابع
              کتابخانه‌ای و دستاوردها را برای جامعه دانشکدگان فارابی یکپارچه
              می‌کند. باشگاه پژوهشیاران نخستین ماژول عملیاتی این پلتفرم است.
            </p>
            <h2>ارتباط با معاونت پژوهشی</h2>
            <p>
              اطلاعات تماس رسمی پس از تأیید مسئول سامانه در این صفحه منتشر
              می‌شود. کاربران عضو می‌توانند درخواست خود را از فضای کار ارسال
              کنند.
            </p>
            <Link href="/workspace/support">ثبت درخواست پشتیبانی</Link>
          </div>
        ) : (
          <form className="form" action="/verify/result">
            <label>
              شناسه گواهی
              <input name="id" dir="ltr" required minLength={20} />
            </label>
            <button>بررسی اعتبار گواهی</button>
          </form>
        )}
      </div>
    </div>
  );
}
