import fs from "node:fs";
import { createHash } from "node:crypto";
const records = [];
function add(kind, title, description, url, editorial = {}) {
  const h = createHash("sha256")
    .update(kind + title + JSON.stringify(editorial))
    .digest("hex");
  records.push({
    id: `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`,
    kind,
    title,
    description,
    external_url: url,
    status: "published",
    editorial,
  });
}
